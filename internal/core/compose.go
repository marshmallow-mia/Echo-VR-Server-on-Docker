package core

import (
	"fmt"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/marshmallow-mia/Echo-VR-Server-on-Docker/v2/pkg/nevr/config"
)

// Compose renders a docker-compose file equivalent to what evr-docker runs,
// for people who prefer to manage the containers themselves. Secrets stay in
// secrets.env, which the file references.
func (a *App) Compose() ([]byte, error) {
	type service struct {
		Image           string            `yaml:"image"`
		ContainerName   string            `yaml:"container_name"`
		User            string            `yaml:"user"`
		Restart         string            `yaml:"restart"`
		StopGracePeriod string            `yaml:"stop_grace_period"`
		ReadOnly        bool              `yaml:"read_only"`
		Tmpfs           []string          `yaml:"tmpfs"`
		CapDrop         []string          `yaml:"cap_drop"`
		SecurityOpt     []string          `yaml:"security_opt"`
		StdinOpen       bool              `yaml:"stdin_open"`
		EnvFile         []string          `yaml:"env_file"`
		Environment     map[string]string `yaml:"environment"`
		Volumes         []string          `yaml:"volumes"`
		Ports           []string          `yaml:"ports"`
		CPUs            float64           `yaml:"cpus,omitempty"`
		MemLimit        string            `yaml:"mem_limit,omitempty"`
		Labels          map[string]string `yaml:"labels"`
	}
	services := map[string]service{}
	secretKeys := map[string]bool{config.EnvDiscordID: true, config.EnvPassword: true, config.EnvHTTPKey: true}
	for _, in := range a.Cfg.Instances {
		if in.Disabled {
			continue
		}
		spec := a.spec(in)
		env := map[string]string{}
		for _, kv := range spec.Env {
			k, v, _ := strings.Cut(kv, "=")
			if !secretKeys[k] {
				env[k] = v
			}
		}
		var ports []string
		for _, p := range spec.Ports {
			host := fmt.Sprint(p.Port)
			if p.HostIP != "" {
				host = p.HostIP + ":" + host
			}
			ports = append(ports, fmt.Sprintf("%s:%d/%s", host, p.Port, p.Proto))
		}
		s := service{
			Image: spec.Image, ContainerName: spec.Name, User: spec.User, Restart: "unless-stopped",
			StopGracePeriod: fmt.Sprintf("%ds", spec.StopTimeout), ReadOnly: true, Tmpfs: []string{"/tmp:rw,exec,size=256m"},
			CapDrop: []string{"ALL"}, SecurityOpt: []string{"no-new-privileges"}, StdinOpen: true,
			EnvFile: []string{filepath.Join(a.Dir, "secrets.env")}, Environment: env, Volumes: spec.Binds, Ports: ports,
			Labels: map[string]string{LabelInstance: in.Name},
		}
		res := a.Cfg.EffectiveResources(in)
		s.CPUs = res.CPUs
		if res.MemoryMB > 0 {
			s.MemLimit = fmt.Sprintf("%dm", res.MemoryMB)
		}
		services[in.Name] = s
	}
	b, err := yaml.Marshal(map[string]any{"name": "echovr", "services": services})
	if err != nil {
		return nil, err
	}
	head := "# Generated by `evr-docker export compose`. Game files, runtimes and per-server\n" +
		"# data live in " + a.Cfg.DataDir + "; install them with evr-docker first. Instance directories\n" +
		fmt.Sprintf("# must be owned by uid %d. Ports are 1:1 on purpose: the game advertises the port it binds.\n", a.Cfg.UID)
	return append([]byte(head), b...), nil
}
